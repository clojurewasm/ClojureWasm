(require (quote clojure.data.json) (quote clojure.string))
(defn rss-mb [] (let [l (first (filter #(.startsWith ^String % "VmRSS") (java.nio.file.Files/readAllLines (java.nio.file.Paths/get "/proc/self/status" (into-array String [])))))]
                  (Long/parseLong (re-find #"\d+" l))))
(defn kb->mb [k] (quot k 1024))
(println "start" (kb->mb (rss-mb)) "MB")
(def big (atom (vec (range 3000000))))
(println "after 3M vector" (kb->mb (rss-mb)) "MB")
(reset! big nil)
(System/gc) (System/gc)
(println "after drop + System/gc" (kb->mb (rss-mb)) "MB")
(dotimes [_ 5] (count (vec (range 3000000))))
(println "after 5 more 3M bursts" (kb->mb (rss-mb)) "MB")
(dotimes [i 200] (count (clojure.data.json/write-str (vec (range 20000)))))
(System/gc)
(println "after 200 x 20k JSON writes" (kb->mb (rss-mb)) "MB")
