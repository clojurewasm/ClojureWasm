;; Editable HAMT must preserve the original and the published snapshot.
(let [source (into {} (map (fn [i] [i i]) (range 200)))
      snapshot (persistent! (assoc! (transient source) 4 :changed 201 :added))
      copied (persistent! (assoc! (transient snapshot) 5 :second))
      removed (persistent! (dissoc! (transient copied) 4))
      s (into #{} (map #(mod % 1000)) (range 20000))
      m (with-meta {} {:origin :into})
      result (into m (map (fn [i] [i i])) (range 200))
      sorted (into (sorted-map) [[2 :b] [1 :a]])
      spent (transient {})]
  (persistent! spent)
  (assert (= 4 (get source 4)))
  (assert (= :changed (get snapshot 4)))
  (assert (= 5 (get snapshot 5)))
  (assert (= :second (get copied 5)))
  (assert (= nil (get removed 4)))
  (assert (= 200 (count removed)))
  (assert (= 1000 (count s)))
  (assert (= {:origin :into} (meta result)))
  (assert (= [1 2] (vec (keys sorted))))
  (assert (try (assoc! spent :x 1) false (catch Exception e true)))
  (println "PASS editable HAMT into"))
