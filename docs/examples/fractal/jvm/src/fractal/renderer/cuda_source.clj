(ns fractal.renderer.cuda-source
  "Promote: the CUDA C source of the escape kernels, generated from the
  formula registry. Pure, so the program text is testable without a GPU.

  One kernel per formula, seed and precision. Each operation of a step
  expression becomes one parenthesised C operation in the same order, and
  NVRTC compiles with --fmad=false, so the fp64 kernels round exactly like
  the JVM. Kernels write the EscapeField only; the palette runs on the host."
  (:require [clojure.string :as str]
            [fractal.formula :as formula]))

(def precisions {:f64 "double" :f32 "float"})

(def seeds
  "Seed -> [cr ci zr0 zi0] as C expressions over px, py, kr, ki."
  {:c-plane ["px" "py" "(REAL)0.0" "(REAL)0.0"]
   :z-plane ["(REAL)kr" "(REAL)ki" "px" "py"]})

(defn c-expr
  "A step expression as C over REAL."
  [expr]
  (cond
    (number? expr) (str "(REAL)(" (double expr) ")")
    (symbol? expr) (str expr)
    :else (let [[op a b] expr]
            (if (= 'abs op)
              (str "fabs(" (c-expr a) ")")
              (str "(" (c-expr a) " " op " " (c-expr b) ")")))))

(defn kernel-name
  "The C identifier of the kernel for formula id, seed and precision."
  [id seed precision]
  (str/replace (str "escape_" id "_" (name seed) "_" (name precision)) "-" "_"))

(defn kernel
  "The C source of one kernel."
  [{:keys [id step]} seed precision]
  (let [[cr ci zr0 zi0] (seeds seed)
        lets (for [[s e] (partition 2 (:let step))] (str "    REAL " s " = " (c-expr e) ";\n"))]
    (str "extern \"C\" __global__ void " (kernel-name id seed precision)
         "(int* counts, double* mag2, int w, int h, double cx, double cy, double scale,\n"
         "    int limit, double kr, double ki) {\n"
         "  typedef " (precisions precision) " REAL;\n"
         "  int x = blockIdx.x * blockDim.x + threadIdx.x;\n"
         "  int y = blockIdx.y * blockDim.y + threadIdx.y;\n"
         "  if (x >= w || y >= h) return;\n"
         "  REAL px = (REAL)cx + ((REAL)x - (REAL)w / (REAL)2.0) * (REAL)scale;\n"
         "  REAL py = (REAL)cy + ((REAL)y - (REAL)h / (REAL)2.0) * (REAL)scale;\n"
         "  REAL cr = " cr ", ci = " ci ";\n"
         "  REAL zr = " zr0 ", zi = " zi0 ";\n"
         "  int n = 0;\n"
         "  while (n < limit && zr * zr + zi * zi <= (REAL)4.0) {\n"
         (apply str lets)
         "    REAL nzr = " (c-expr (:zr step)) ";\n"
         "    REAL nzi = " (c-expr (:zi step)) ";\n"
         "    zr = nzr;\n"
         "    zi = nzi;\n"
         "    n++;\n"
         "  }\n"
         "  counts[y * w + x] = n;\n"
         "  mag2[y * w + x] = (double)(zr * zr + zi * zi);\n"
         "}\n")))

(defn kernels
  "[formula-id seed precision] -> kernel name, for every kernel of registry."
  ([] (kernels formula/registry))
  ([registry]
   (into {} (for [id (keys registry) seed (keys seeds) p (keys precisions)]
              [[id seed p] (kernel-name id seed p)]))))

(defn program
  "The whole CUDA program for registry."
  ([] (program formula/registry))
  ([registry]
   (str "// Generated by fractal.renderer.cuda-source from fractal.formula/registry.\n\n"
        (str/join "\n" (for [f (vals registry) seed (keys seeds) p (keys precisions)]
                         (kernel f seed p))))))
